export function getIdentityInitials(name: string) {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? "")
    .join("");
}

export function isRiskIdentity(identity: AssetIdentity) {
  if (identity.riskScore >= 70) {
    return true;
  }

  if (identity.status === "locked" || identity.status === "stale") {
    return true;
  }

  if (identity.privileged && identity.mfaEnabled === false) {
    return true;
  }

  return false;
}

export type IdentityAttentionKey =
  | "privileged-mfa-gap"
  | "dormant-privileged"
  | "guest-mfa-off";

export type IdentityAttentionFilter = {
  label: string;
  description: string;
  /** Tab that best scopes the results when the chip is activated. */
  tab: "all" | "service" | "privileged" | "guest";
  matches: (identity: AssetIdentity) => boolean;
};

export const identityAttentionFilters: Record<
  IdentityAttentionKey,
  IdentityAttentionFilter
> = {
  "privileged-mfa-gap": {
    label: "Privileged without MFA",
    description: "Elevated access with no second factor enrolled.",
    tab: "privileged",
    matches: (identity) =>
      identity.privileged && identity.mfaEnabled === false,
  },
  "dormant-privileged": {
    label: "Dormant privileged",
    description: "Privileged accounts that are stale or locked.",
    tab: "privileged",
    matches: (identity) =>
      identity.privileged &&
      (identity.status === "stale" || identity.status === "locked"),
  },
  "guest-mfa-off": {
    label: "Guests without MFA",
    description: "External identities with MFA disabled.",
    tab: "guest",
    matches: (identity) =>
      identity.kind === "guest" && identity.mfaEnabled === false,
  },
};

export function getIdentityListStats(
  identities: AssetIdentity[],
): IdentityListStat[] {
  const total = identities.length;
  const privileged = identities.filter((identity) => identity.privileged).length;
  const mfaGaps = identities.filter(
    (identity) => identity.mfaEnabled === false,
  ).length;
  const atRisk = identities.filter(isRiskIdentity).length;

  return [
    {
      title: "Total identities",
      value: String(total),
      delta: 4.1,
      context: "vs last week",
      preferLower: false,
    },
    {
      title: "Privileged",
      value: String(privileged),
      delta: 1.8,
      context: "vs last week",
      preferLower: true,
    },
    {
      title: "MFA gaps",
      value: String(mfaGaps),
      delta: -6.4,
      context: "vs last week",
      preferLower: true,
    },
    {
      title: "At risk",
      value: String(atRisk),
      delta: -2.7,
      context: "vs last week",
      preferLower: true,
    },
  ];
}

export function getIdentitiesByTab(
  identities: AssetIdentity[],
  tab: "all" | "service" | "privileged" | "guest",
) {
  switch (tab) {
    case "service":
      return identities.filter((identity) => identity.kind === "service");
    case "privileged":
      return identities.filter((identity) => identity.privileged);
    case "guest":
      return identities.filter((identity) => identity.kind === "guest");
    default:
      return identities;
  }
}
