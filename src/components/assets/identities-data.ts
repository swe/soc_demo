export type IdentityKind = "user" | "service" | "guest";

export type IdentityStatus = "active" | "disabled" | "locked" | "stale";

export type IdentitySource =
  | "Entra ID"
  | "Okta"
  | "Active Directory"
  | "AWS IAM"
  | "Local";

export type AssetIdentity = {
  id: string;
  displayName: string;
  /** UPN, email, or service principal / client id. */
  principal: string;
  kind: IdentityKind;
  source: IdentitySource;
  status: IdentityStatus;
  department: string;
  owner: string;
  title: string;
  privileged: boolean;
  /** null = not applicable (typical for some service accounts). */
  mfaEnabled: boolean | null;
  avatar?: string;
  lastSeenLabel: string;
  lastSeenValue: number;
  riskScore: number;
  /** Directory / security groups shown in the detail sheet. */
  groups: string[];
  lastPasswordChangeLabel: string;
  signInLocation: string;
  linkedDevices: string[];
  /** Short analyst-facing risk rationale. Empty when nothing noteworthy. */
  notes: string;
};

export const identityKindLabels: Record<IdentityKind, string> = {
  user: "User",
  service: "Service account",
  guest: "Guest",
};

export const identityStatusLabels: Record<IdentityStatus, string> = {
  active: "Active",
  disabled: "Disabled",
  locked: "Locked",
  stale: "Stale",
};

export const identityStatusColors: Record<IdentityStatus, string> = {
  active: "#22c55e",
  disabled: "#71717a",
  locked: "#ef4444",
  stale: "#f59e0b",
};

export type IdentityListStat = {
  title: string;
  value: string;
  delta: number;
  context: string;
  /** When true, a falling trend is healthy (shown in green). */
  preferLower: boolean;
};

type IdentitySeed = Omit<
  AssetIdentity,
  | "privileged"
  | "mfaEnabled"
  | "groups"
  | "lastPasswordChangeLabel"
  | "signInLocation"
  | "linkedDevices"
  | "notes"
> &
  Partial<
    Pick<
      AssetIdentity,
      | "privileged"
      | "mfaEnabled"
      | "groups"
      | "lastPasswordChangeLabel"
      | "signInLocation"
      | "linkedDevices"
      | "notes"
    >
  >;

const defaultGroups: Record<IdentityKind, string[]> = {
  user: ["All Employees", "SSO Users"],
  service: ["Service Principals"],
  guest: ["External Collaborators"],
};

const defaultSignInLocation: Record<IdentityKind, string> = {
  user: "HQ · New York",
  service: "Automation · us-east-1",
  guest: "Remote",
};

const defaultPasswordChange: Record<IdentityKind, string> = {
  user: "38 days ago",
  service: "Rotated 30 days ago",
  guest: "62 days ago",
};

function defineIdentity(seed: IdentitySeed): AssetIdentity {
  return {
    privileged: false,
    mfaEnabled: seed.kind === "service" ? null : true,
    groups: defaultGroups[seed.kind],
    lastPasswordChangeLabel: defaultPasswordChange[seed.kind],
    signInLocation: defaultSignInLocation[seed.kind],
    linkedDevices: [],
    notes: "",
    ...seed,
  };
}

